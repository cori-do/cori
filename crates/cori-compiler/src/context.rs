//! Generates `.cori/context.ts` and `.cori/deno.json` for a workflow folder.
use crate::dag::{Dag, Node};
use crate::manifest::{self, Manifest};
use std::collections::BTreeMap;
use std::fmt::Write;

fn var(index: usize) -> String { format!("s{:02}", index) }

/// TypeScript expression that names a step's declaration object.
fn type_expr(n: &Node, by_name: &BTreeMap<&str, &Node>) -> String {
    match &n.nested_in {
        None => format!("typeof {}", var(n.index)),
        Some(p) => {
            let parent = by_name[p.as_str()];
            let base = type_expr(parent, by_name);
            let slot = n.slot.clone().unwrap_or_default();
            if let Some(label) = slot.strip_prefix("cases.") { format!("({base})[\"cases\"][{label:?}]") } else { format!("({base})[{slot:?}]") }
        }
    }
}

fn output_type(n: &Node, by_name: &BTreeMap<&str, &Node>) -> Option<String> {
    let t = type_expr(n, by_name);
    let base = match n.kind.as_str() {
        "branch" | "switch" | "wait" => return None,
        "map" => format!("{{ items: Out<({t})[\"each\"]>[] }}"),
        "loop" => format!("Out<({t})[\"body\"]>"),
        "try" => format!("Out<({t})[\"body\"]>"),
        _ => format!("Out<{t}>"),
    };
    Some(if n.conditional { format!("{base} | undefined") } else { base })
}

pub fn context_dts(m: &Manifest, dag: &Dag, step_files: &[(usize, String)], sdk_import: &str, connectors: &[serde_json::Value]) -> String {
    let by_name: BTreeMap<&str, &Node> = dag.nodes.iter().map(|n| (n.name.as_str(), n)).collect();
    let mut s = String::new();
    writeln!(s, "// generated by `cori check` for workflow `{}` — do not edit", m.id).unwrap();
    writeln!(s, "import type {{ z }} from \"zod\";").unwrap();
    // `CoriFile` only where a parameter takes files: the context of every other workflow reads as before
    let files = if m.parameters.iter().any(|p| p.is_file()) { "CoriFile, " } else { "" };
    writeln!(s, "import type {{ {files}RunInfo, UserInfo }} from \"{sdk_import}\";").unwrap();
    for (i, f) in step_files { writeln!(s, "import {} from \"../steps/{f}\";", var(*i)).unwrap(); }
    writeln!(s, "\ntype Out<S> = S extends {{ output: infer Z extends z.ZodTypeAny }} ? z.output<Z> : never;").unwrap();
    // Params
    writeln!(s, "\nexport type Params = {{").unwrap();
    for p in &m.parameters {
        let opt = if !p.required || p.default.is_some() { "?" } else { "" };
        writeln!(s, "  readonly {}{opt}: {};", p.name, manifest::ts_type(p)).unwrap();
    }
    writeln!(s, "}};").unwrap();
    // StepOutputs
    writeln!(s, "\nexport type StepOutputs = {{").unwrap();
    let mut names: Vec<&Node> = dag.nodes.iter().collect();
    for n in &names { if let Some(t) = output_type(n, &by_name) { writeln!(s, "  readonly {}: {t};", n.name).unwrap(); } }
    writeln!(s, "}};").unwrap();
    writeln!(s, "export type StepName = keyof StepOutputs | {};", {
        let others: Vec<String> = dag.nodes.iter().filter(|n| matches!(n.kind.as_str(), "branch" | "switch" | "wait")).map(|n| format!("{:?}", n.name)).collect();
        if others.is_empty() { "never".to_string() } else { others.join(" | ") }
    }).unwrap();
    // PredecessorsOf
    writeln!(s, "\nexport type PredecessorsOf<N extends StepName> =").unwrap();
    names.sort_by_key(|n| (n.index, n.nested_in.is_some()));
    for n in &names {
        let preds: Vec<String> = dag.predecessors[&n.name].iter().filter(|p| by_name[p.as_str()].kind != "branch" && by_name[p.as_str()].kind != "switch" && by_name[p.as_str()].kind != "wait").map(|p| format!("{p:?}")).collect();
        writeln!(s, "  N extends {:?} ? {} :", n.name, if preds.is_empty() { "never".to_string() } else { preds.join(" | ") }).unwrap();
    }
    writeln!(s, "  never;").unwrap();
    // ItemOf: each step nested in a map gets the element type of the array the map iterates.
    // Derived from the `over` binding's static reference (not `typeof map.over`) to avoid a circular type.
    writeln!(s, "\nexport type ItemOf<N extends StepName> =").unwrap();
    for n in &names {
        if let Some(p) = &n.nested_in {
            let parent = by_name[p.as_str()];
            if parent.kind == "map" && n.slot.as_deref() == Some("each") {
                let over_refs: Vec<&String> = parent.refs.iter().collect();
                let ty = match over_refs.as_slice() {
                    [one] => ref_to_type(one).map(|t| format!("{t}[number]")),
                    _ => None,
                };
                writeln!(s, "  N extends {:?} ? {} :", n.name, ty.unwrap_or_else(|| "unknown /* map.over must be a single context reference; compute the array in a code step */".into())).unwrap();
            }
        }
    }
    writeln!(s, "  never;").unwrap();
    writeln!(s, "\nexport type Ctx<N extends StepName> = {{\n  readonly params: Params;\n  readonly user: UserInfo;\n  readonly run: RunInfo;\n  readonly steps: Pick<StepOutputs, Extract<PredecessorsOf<N>, keyof StepOutputs>>;\n  readonly item: ItemOf<N>;\n}};").unwrap();
    // Declared connector tools: `step.mcp({ connector, tool, input })` is typed against the tool's input schema
    // through declaration merging into the SDK's `ConnectorTools` (empty by default, so undeclared tools stay open).
    let typed: Vec<&serde_json::Value> = connectors.iter().filter(|c| c["tools"].as_array().map(|a| !a.is_empty()).unwrap_or(false)).collect();
    if !typed.is_empty() {
        writeln!(s, "\n// Tool inputs of the connectors the org declared (snapshotted by `cori connectors add`); a wrong argument fails `check`.").unwrap();
        writeln!(s, "declare module {sdk_import:?} {{\n  interface ConnectorTools {{").unwrap();
        for c in typed {
            let name = c["name"].as_str().unwrap_or("");
            let tools: Vec<String> = c["tools"].as_array().unwrap().iter().filter_map(|t| { let n = t["name"].as_str()?; let ty = crate::tsgen::ts(t.get("inputSchema").unwrap_or(&serde_json::json!({ "type": "object" }))); Some(format!("      readonly {}: {ty};", crate::tsgen::key(n))) }).collect();
            writeln!(s, "    readonly {}: {{\n{}\n    }};", crate::tsgen::key(name), tools.join("\n")).unwrap();
        }
        writeln!(s, "  }}\n}}").unwrap();
    }
    s
}

pub fn deno_json(sdk_path: &str) -> String {
    let sdk = if sdk_path.starts_with("file://") || sdk_path.starts_with("./") || sdk_path.starts_with("../") { sdk_path.to_string() } else { format!("file://{sdk_path}") };
    format!("{{\n  \"imports\": {{\n    \"@cori-do/sdk\": \"{sdk}\",\n    \"zod\": \"npm:zod@4.4.3\"\n  }},\n  \"compilerOptions\": {{ \"strict\": true, \"noImplicitAny\": true, \"lib\": [\"deno.ns\", \"esnext\"] }},\n  \"unstable\": [\"sloppy-imports\"],\n  \"nodeModulesDir\": \"none\"\n}}\n")
}

/// `steps.by_department.groups` → `NonNullable<StepOutputs["by_department"]>["groups"]`; `params.rows` → `Params["rows"]`.
fn ref_to_type(r: &str) -> Option<String> {
    let mut parts = r.split('.');
    let root = parts.next()?;
    let mut t = match root { "steps" => { let name = parts.next()?; format!("NonNullable<StepOutputs[{name:?}]>") } "params" => "Params".to_string(), "user" => "UserInfo".to_string(), "run" => "RunInfo".to_string(), _ => return None };
    for p in parts {
        if p.starts_with('[') { t = format!("{t}[number]"); continue; }
        let (field, indexed) = match p.find('[') { Some(i) => (&p[..i], true), None => (p, false) };
        t = format!("NonNullable<{t}>[{field:?}]");
        if indexed { t = format!("{t}[number]"); }
    }
    Some(t)
}
