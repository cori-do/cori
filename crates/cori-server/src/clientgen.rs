//! `cori gen client`: a typed TypeScript client from the deployed workflows' parameters, result declaration and output schemas.
use crate::bundles::WorkflowEntry;
use serde_json::Value;
use cori_compiler::tsgen::key;
use std::fmt::Write;

fn pascal(s: &str) -> String { s.split(['_', '-', ' ']).filter(|p| !p.is_empty()).map(|p| { let mut c = p.chars(); c.next().map(|f| f.to_uppercase().collect::<String>() + c.as_str()).unwrap_or_default() }).collect() }
fn camel(s: &str) -> String { let p = pascal(s); let mut c = p.chars(); c.next().map(|f| f.to_lowercase().collect::<String>() + c.as_str()).unwrap_or_default() }
fn snake(s: &str) -> String { s.trim().to_lowercase().chars().map(|c| if c.is_alphanumeric() { c } else { '_' }).collect::<String>().split('_').filter(|p| !p.is_empty()).collect::<Vec<_>>().join("_") }

/// JSON Schema (Zod 4 export) → TypeScript type expression, arrays mutable (a front's code may sort them).
fn ts_of(schema: &Value) -> String { cori_compiler::tsgen::ts_with(schema, cori_compiler::tsgen::Style { readonly_arrays: false }) }

/// A parameter as the run's result names it back (`params.x`): a file is its reference.
fn param_ts(p: &cori_compiler::manifest::Parameter) -> String { cori_compiler::manifest::ts_type(p) }

/// A parameter as a front gives it to `run()` / `start()`: a file may be a browser `File`, which the client uploads first.
fn input_ts(p: &cori_compiler::manifest::Parameter) -> String {
    match p.ty.as_str() { "file" => "CoriFileInput".into(), "files" => "readonly CoriFileInput[]".into(), _ => param_ts(p) }
}

fn path_type(path: &str, w: &WorkflowEntry) -> String {
    let mut parts = path.split('.');
    match parts.next() {
        Some("steps") => {
            let step = match parts.next() { Some(s) => s, None => return "unknown".into() };
            let mut cur = match w.compiled.schemas.get(step) { Some(s) => s.clone(), None => return "unknown".into() };
            for p in parts { cur = cur.get("properties").and_then(|ps| ps.get(p)).cloned().unwrap_or(Value::Null); }
            if cur.is_null() { "unknown".into() } else { ts_of(&cur) }
        }
        Some("params") => parts.next().and_then(|n| w.compiled.manifest.parameters.iter().find(|p| p.name == n)).map(param_ts).unwrap_or("unknown".into()),
        _ => "unknown".into(),
    }
}

pub fn client_ts(app: &str, workflows: &[WorkflowEntry]) -> String {
    let body = client_body(app, workflows);
    // the file types only where the client names them (a front's tsconfig refuses unused imports): every other app's
    // client reads as before
    let uses = |t: &str| body.match_indices(t).any(|(i, _)| !body[i + t.len()..].starts_with(|c: char| c.is_alphanumeric() || c == '_'));
    let extra: String = ["CoriFile", "CoriFileInput"].iter().filter(|t| uses(t)).map(|t| format!(", type {t}")).collect();
    format!("// generated by `cori gen client` for app `{app}` — do not edit\nimport {{ createCoriClient, type RunView{extra} }} from \"@cori-do/client\";\n\n{body}")
}

fn client_body(app: &str, workflows: &[WorkflowEntry]) -> String {
    let mut s = String::new();
    writeln!(s, "export const cori = createCoriClient({{ app: {app:?} }});\n").unwrap();
    for w in workflows {
        let Some(ep) = &w.compiled.manifest.endpoint else { continue };
        let name = pascal(&w.id);
        writeln!(s, "export type {name}Input = {{").unwrap();
        for p in &w.compiled.manifest.parameters { let opt = if !p.required || p.default.is_some() { "?" } else { "" }; writeln!(s, "  {}{opt}: {};", key(&p.name), input_ts(p)).unwrap(); }
        writeln!(s, "}};").unwrap();
        writeln!(s, "export type {name}Outputs = {{").unwrap();
        for n in w.compiled.dag.nodes.iter().filter(|n| w.compiled.schemas.contains_key(&n.name)) { let opt = if n.conditional { "?" } else { "" }; writeln!(s, "  {}{opt}: {};", key(&n.name), ts_of(&w.compiled.schemas[&n.name])).unwrap(); }
        writeln!(s, "}};").unwrap();
        writeln!(s, "export type {name}Values = {{").unwrap();
        // one key per label, snake_cased (the first of two labels with the same key wins, as in the rendered result)
        let mut seen = std::collections::BTreeSet::new();
        if let Some(r) = &w.compiled.manifest.result { for f in r.get("fields").and_then(|f| f.as_array()).cloned().unwrap_or_default().iter().chain(r.get("sections").and_then(|f| f.as_array()).cloned().unwrap_or_default().iter()) {
            let label = f.get("label").and_then(|l| l.as_str()).unwrap_or("value"); let path = f.get("path").and_then(|p| p.as_str()).unwrap_or("");
            let opt = if f.get("optional").and_then(|o| o.as_bool()).unwrap_or(false) { "?" } else { "" };
            let k = snake(label);
            if !seen.insert(k.clone()) { continue; }
            writeln!(s, "  {}{opt}: {};", key(&k), path_type(path, w)).unwrap();
        } }
        writeln!(s, "}};").unwrap();
        writeln!(s, "/** {} — endpoint {} · auth {} */", w.compiled.manifest.description.trim().replace("*/", "*\\/"), ep.mode, ep.auth).unwrap();
        writeln!(s, "export const {} = cori.workflow<{name}Input, {name}Values, {name}Outputs>({:?}, {{ mode: {:?} }});", camel(&w.id), w.id, ep.mode).unwrap();
        writeln!(s, "export type {name}Run = RunView<{name}Values, {name}Outputs>;\n").unwrap();
    }
    s
}
